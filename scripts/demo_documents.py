def members_csv(p):
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer)
    writer.writerow(["name", "email", "department", "role"])
    names = ["林", "周", "陈", "许", "顾", "宋", "陆", "沈", "苏", "叶", "韩", "唐"]
    for i in range(p['count']):
        writer.writerow([f"{names[i % len(names)]}测试{i + 1:03d}", f"{p['code'].lower()}.member{i + 1:03d}@xinglan.example.test",
                         p['departments'][i % len(p['departments'])], "admin" if i == 0 else "manager" if i % 10 == 0 else "viewer" if i % 11 == 0 else "member"])
    return buffer.getvalue()


