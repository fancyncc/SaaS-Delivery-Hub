def document(key, title, module, sections, *, version=1, active=True, project=None):
    body = f"# {title}\n\n版本：v{version}｜资料编号：{key}｜编制日期：2026-09-11\n\n> {NOTICE}\n\n"
    body += "\n\n".join(f"## {heading}\n\n{text}" for heading, text in sections)
    return dict(key=key, title=title, module=module, body=body + "\n", version=version, active=active, project=project)


