def all_documents():
    return company_documents() + [d for p in PROJECTS for d in project_documents(p)]


def write_files(root):
    docs = all_documents()
    for doc in docs:
        folder = root / "文档" / (doc['project'] or "公司制度")
        folder.mkdir(parents=True, exist_ok=True)
        (folder / f"{doc['key']}_{doc['title']}_v{doc['version']}.md").write_text(doc['body'], encoding='utf-8')
    csv_dir = root / "导入样本"
    csv_dir.mkdir(parents=True, exist_ok=True)
    for p in PROJECTS:
        (csv_dir / f"{p['code']}_members_valid.csv").write_text(members_csv(p), encoding='utf-8-sig')
        folder = root / "文档" / p['code']
        (folder / f"{p['code']}_项目字段.json").write_text(json.dumps(project_payload(p), ensure_ascii=False, indent=2), encoding='utf-8')
    (csv_dir / "XL-104_members_invalid.csv").write_text(bad_members_csv(), encoding='utf-8-sig')
    return docs
